"""Spec 020 SC-005: the navigator evaluation set and its deterministic screens.

``fixtures/navigator/eval_v1.json`` holds ~48 synthetic cases
(contracts/navigator.md §5). ``screen_recorded_outputs`` runs the §2
validation and the automatic screens over a file of recorded outputs and
returns **aggregate scores only** (never a proposal's text). CI runs it over
``recorded_v1_sample.json``: hand-written synthetic outputs, not model output.
No test here calls a provider.

Real cells are generated by the owner only (cloud runs spend provider money and
are approval-gated, never unattended or from a subagent) and screened with
``BRAIN_BUDDY_NAVIGATOR_RECORDED=<path> pytest tests/test_review_navigator_eval.py``;
blind grading (accept / edit / reject) and the ≥ 50 % gate stay manual.
"""

from __future__ import annotations

import json
import os
import re
import unicodedata
from collections import Counter
from pathlib import Path
from typing import Any

import allure

from app.modules.tasks.formulation import formulation_key
from app.modules.tasks.navigator import (
    MAX_PROPOSAL_CHARS,
    NavigatorInput,
    build_navigator_input,
    validate_navigator_output,
)
from app.schemas.review import NavigatorSuggestionRequest

FIXTURES = Path(__file__).parent / "fixtures" / "navigator"
EVAL_SET = FIXTURES / "eval_v1.json"
SAMPLE = FIXTURES / "recorded_v1_sample.json"
STALL_REASONS = {
    None,
    "unclear",
    "too_big",
    "missing_info",
    "waiting_on_someone",
    "no_energy",
    "no_longer_matters",
}


def load(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as handle:
        data: dict[str, Any] = json.load(handle)
    return data


def case_input(case: dict[str, Any]) -> NavigatorInput:
    """The FR-019 input of a case, exactly as a client would send it."""

    request = NavigatorSuggestionRequest.model_validate(request_body(case))
    return build_navigator_input(request)


_SMART_ADD = re.compile(r"(?:^|[\s(\[{])[#@!]\S")


def _shape_ok(text: str) -> bool:
    """The screen's own check of rule 1 (independent of the validator)."""

    stripped = text.strip()
    return (
        bool(stripped)
        and len(stripped.splitlines()) == 1
        and len(stripped) <= MAX_PROPOSAL_CHARS
        and _SMART_ADD.search(stripped) is None
    )


def _entity_like(token: str, *, first: bool) -> bool:
    letters = [char for char in token if char.isalpha()]
    return (
        (bool(letters) and letters[0].isupper() and not first)
        or any(char.isdecimal() for char in token)
        or any(unicodedata.category(char) == "Sc" for char in token)
    )


def invented(text: str, case: dict[str, Any], navigator_input: NavigatorInput) -> bool:
    """The invented-fact screen: a name, number or amount not covered by the
    case's ``allowed_entities``, its title, project name or sibling titles.

    Facts from the notes count only when the fixture lists them as allowed, so
    the curated list, not the validator, is the reference here.
    """

    covered = [
        f" {formulation_key(value)} "
        for value in (
            *case["allowed_entities"],
            navigator_input.task_title,
            navigator_input.project_name,
            *navigator_input.open_task_titles,
        )
        if value
    ]
    for index, token in enumerate(text.split()):
        key = formulation_key(token)
        if (
            key
            and _entity_like(token, first=index == 0)
            and not any(f" {key} " in value for value in covered)
        ):
            return True
    return False


def _empty_bucket() -> dict[str, Any]:
    return {
        "outputs": 0,
        "returned": {"proposals": 0, "question": 0, "malformed": 0},
        "kind_match": 0,
        "raw_invented_facts": 0,
    }


def screen_recorded_outputs(
    eval_set: dict[str, Any], recorded: dict[str, Any]
) -> dict[str, Any]:
    """The deterministic screen runner (aggregate scores only).

    For every recorded output: the §2 validation (what is shown, or the
    question, or ``malformed``), why each raw proposal was dropped (shape,
    duplicate, grounding), the returned kind against ``expected_kind``, and
    the invented-fact screen before and after validation.
    """

    cases = {case["id"]: case for case in eval_set["cases"]}
    report: dict[str, Any] = {
        "source": recorded["source"],
        "eval_set": recorded["eval_set"],
        "prompt_version": recorded["prompt_version"],
        "outputs": 0,
        "unknown_cases": 0,
        "raw_proposals": 0,
        "dropped": {"shape": 0, "duplicate": 0, "grounding": 0},
        "shown_proposals": 0,
        "returned": {"proposals": 0, "question": 0, "malformed": 0},
        "kind_match": 0,
        "raw_invented_facts": 0,
        "invented_facts_after_validation": 0,
        "duplicates_after_validation": 0,
        "shape_violations_after_validation": 0,
        "by_language": {},
    }
    for output in recorded["outputs"]:
        case = cases.get(output["case_id"])
        if case is None:
            report["unknown_cases"] += 1
            continue
        _screen_one(report, case, output)
    return report


def _screen_one(
    report: dict[str, Any], case: dict[str, Any], output: dict[str, Any]
) -> None:
    navigator_input = case_input(case)
    proposals = list(output["proposals"])
    bucket = report["by_language"].setdefault(case["language"], _empty_bucket())
    report["outputs"] += 1
    bucket["outputs"] += 1
    report["raw_proposals"] += len(proposals)
    seen = {formulation_key(navigator_input.task_title or "")}
    seen.update(formulation_key(title) for title in navigator_input.open_task_titles)
    for proposal in proposals:
        if invented(proposal, case, navigator_input):
            report["raw_invented_facts"] += 1
            bucket["raw_invented_facts"] += 1
        key = formulation_key(proposal)
        if not _shape_ok(proposal):
            report["dropped"]["shape"] += 1
        elif key in seen:
            report["dropped"]["duplicate"] += 1
        else:
            seen.add(key)
            if (
                validate_navigator_output(
                    navigator_input, proposals=[proposal], clarifying_question=None
                )
                is None
            ):
                report["dropped"]["grounding"] += 1
    result = validate_navigator_output(
        navigator_input,
        proposals=proposals,
        clarifying_question=output["clarifying_question"],
    )
    if result is None:
        returned = "malformed"
    elif result.proposals is not None:
        returned = "proposals"
        _screen_shown(report, case, navigator_input, result.proposals)
    else:
        returned = "question"
    report["returned"][returned] += 1
    bucket["returned"][returned] += 1
    if returned == case["expected_kind"]:
        report["kind_match"] += 1
        bucket["kind_match"] += 1


def _screen_shown(
    report: dict[str, Any],
    case: dict[str, Any],
    navigator_input: NavigatorInput,
    shown: tuple[str, ...],
) -> None:
    report["shown_proposals"] += len(shown)
    sent = {formulation_key(navigator_input.task_title or "")}
    sent.update(formulation_key(title) for title in navigator_input.open_task_titles)
    keys = [formulation_key(text) for text in shown]
    report["duplicates_after_validation"] += sum(key in sent for key in keys) + (
        len(keys) - len(set(keys))
    )
    report["shape_violations_after_validation"] += sum(
        not _shape_ok(text) for text in shown
    ) + max(0, len(shown) - 3)
    report["invented_facts_after_validation"] += sum(
        invented(text, case, navigator_input) for text in shown
    )


# --------------------------------------------------------------- the set
def test_020_SC_005_eval_set_has_the_planned_shape() -> None:
    """About 48 cases: 24 RU, 12 EN, 12 code-switched; every stall reason and
    none; about 25 % expecting one question; entities and none; 0/5/20
    siblings; every case with ``expected_kind`` and ``allowed_entities``."""

    data = load(EVAL_SET)
    cases = data["cases"]
    assert data["schema"] == "brainbuddy-navigator-eval/v1"
    assert data["prompt_version"] == "navigator-prompt/v1"
    assert len(cases) == 48
    assert len({case["id"] for case in cases}) == 48
    assert Counter(case["language"] for case in cases) == {
        "ru": 24,
        "en": 12,
        "ru-en": 12,
    }
    assert {case["stall_reason"] for case in cases} == STALL_REASONS
    questions = sum(case["expected_kind"] == "question" for case in cases)
    assert 10 <= questions <= 14
    assert {case["expected_kind"] for case in cases} == {"proposals", "question"}
    with_entities = sum(bool(case["allowed_entities"]) for case in cases)
    assert 16 <= with_entities <= 32
    assert {len(case["sibling_titles"]) for case in cases} == {0, 5, 20}
    assert {case["kind"] for case in cases} == {
        "first_step",
        "reformulate",
        "project_next_action",
    }


def test_020_SC_005_every_case_is_a_valid_fr_019_request() -> None:
    """Each case builds a strict ``NavigatorSuggestionRequest`` (no extra
    field, no language) and every allowed entity occurs in its own input."""

    for case in load(EVAL_SET)["cases"]:
        request = NavigatorSuggestionRequest.model_validate(request_body(case))
        assert request.kind == case["kind"]
        haystack = " " + " ".join(input_keys(case_input(case))) + " "
        for entity in case["allowed_entities"]:
            assert f" {formulation_key(entity)} " in haystack, (case["id"], entity)


def request_body(case: dict[str, Any]) -> dict[str, Any]:
    body: dict[str, Any] = {
        "kind": case["kind"],
        "consent": {"external_processing_allowed": True, "provider": "openai"},
    }
    if case["kind"] != "project_next_action":
        body["task"] = {
            "title": case["title"],
            "notes": case["notes"],
            "stall_reason": case["stall_reason"],
        }
    if case["project_name"] is not None:
        body["project"] = {
            "name": case["project_name"],
            "open_task_titles": case["sibling_titles"],
        }
    return body


def input_keys(navigator_input: NavigatorInput) -> list[str]:
    fields = (
        navigator_input.task_title,
        navigator_input.task_notes,
        navigator_input.project_name,
        *navigator_input.open_task_titles,
    )
    return [formulation_key(value) for value in fields if value]


# ------------------------------------------------------------- the runner
def test_020_SC_005_screen_runner_scores_the_synthetic_sample() -> None:
    """The runner's aggregate over the synthetic sample: what the validation
    dropped and why, kinds returned against ``expected_kind``, and invented
    facts before and after validation (0 after, the automatic half of the
    "0 confirmed invented facts" gate)."""

    with allure.step("screen the synthetic recorded sample"):
        report = screen_recorded_outputs(load(EVAL_SET), load(SAMPLE))
        attach_report(report)
    assert report["source"] == "synthetic"
    assert report["outputs"] == 14
    assert report["raw_proposals"] == 26
    assert report["dropped"] == {"shape": 3, "duplicate": 2, "grounding": 6}
    assert report["shown_proposals"] == 15
    assert report["returned"] == {"proposals": 12, "question": 1, "malformed": 1}
    assert report["kind_match"] == 12
    assert report["raw_invented_facts"] == 6
    assert report["invented_facts_after_validation"] == 0
    assert report["by_language"]["ru"]["outputs"] == 7
    assert report["by_language"]["en"]["outputs"] == 4
    assert report["by_language"]["ru-en"]["outputs"] == 3
    assert report["by_language"]["ru"]["raw_invented_facts"] == 3


def test_020_SC_005_report_is_aggregate_only() -> None:
    """Nothing a model wrote, and no case text, appears in the report."""

    eval_set = load(EVAL_SET)
    recorded = load(SAMPLE)
    rendered = json.dumps(screen_recorded_outputs(eval_set, recorded))
    for output in recorded["outputs"]:
        for text in [*output["proposals"], output["clarifying_question"] or ""]:
            for word in text.split():
                if len(word) > 6:
                    assert word not in rendered
    for case in eval_set["cases"]:
        assert case["id"] not in rendered


def test_020_FR_021_screens_hold_for_any_recorded_file() -> None:
    """For the sample, or an owner-supplied recording named by
    ``BRAIN_BUDDY_NAVIGATOR_RECORDED``: after validation no invented fact, no
    duplicate of a sent sibling, at most 3 one-line proposals of ≤ 200."""

    path = Path(os.environ.get("BRAIN_BUDDY_NAVIGATOR_RECORDED", str(SAMPLE)))
    eval_set = load(EVAL_SET)
    recorded = load(path)
    report = screen_recorded_outputs(eval_set, recorded)
    assert report["invented_facts_after_validation"] == 0
    assert report["duplicates_after_validation"] == 0
    assert report["shape_violations_after_validation"] == 0
    assert report["unknown_cases"] == 0
    with allure.step("the aggregate read-out"):
        attach_report(report)
        print(json.dumps(report, sort_keys=True))


def attach_report(report: dict[str, Any]) -> None:
    """The aggregate report as step evidence (numbers only, never text)."""

    allure.attach(
        json.dumps(report, sort_keys=True, indent=2),
        name="screen report (aggregate)",
        attachment_type=allure.attachment_type.JSON,
    )
