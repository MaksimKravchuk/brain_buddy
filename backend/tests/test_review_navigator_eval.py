class RecordingError(ValueError):
    """A recording that must not be scored (incomplete or mismatched)."""


def _metadata_problems(eval_set: dict[str, Any], recorded: dict[str, Any]) -> list[str]:
    expected = {
        "schema": RECORDING_SCHEMA,
        "eval_set": EVAL_SET_ID,
        "prompt_version": PROMPT_VERSION,
    }
    assert eval_set["prompt_version"] == PROMPT_VERSION
    return [
        f"{field} is {recorded.get(field)!r}, expected {value!r}"
        for field, value in expected.items()
        if recorded.get(field) != value
    ]


def _cell_languages(
    eval_set: dict[str, Any], recorded: dict[str, Any]
) -> tuple[set[str], list[str]]:
    """The languages of the recording's cell (``languages``, default all)."""

    known = {case["language"] for case in eval_set["cases"]}
    declared = recorded.get("languages")
    if declared is None:
        return known, []
    unknown = sorted(set(declared) - known) if isinstance(declared, list) else []
    if not isinstance(declared, list) or not declared or unknown:
        return known, [
            f"languages {declared!r} must be a non-empty subset of {sorted(known)}"
        ]
    return set(declared), []


def validate_recording(
    eval_set: dict[str, Any], recorded: dict[str, Any], *, require_complete: bool
) -> None:
    """Refuse a recording that must not be scored (contracts/navigator.md §5).

    The schema, ``eval_set`` and ``prompt_version`` must be the current ones;
    every output must name a case of the recording's cell (the languages in
    ``languages``, default every case), at most once; with
    ``require_complete`` every case of the cell needs exactly one output.
    Raises ``RecordingError`` naming every missing, duplicate or unknown id.
    """

    problems = _metadata_problems(eval_set, recorded)
    languages, language_problems = _cell_languages(eval_set, recorded)
    problems += language_problems
    applicable = {
        case["id"] for case in eval_set["cases"] if case["language"] in languages
    }
    counts = Counter(output["case_id"] for output in recorded["outputs"])
    duplicate = sorted(case_id for case_id, n in counts.items() if n > 1)
    unknown = sorted(set(counts) - applicable)
    missing = sorted(applicable - set(counts)) if require_complete else []
    for label, ids in (
        ("missing", missing),
        ("duplicate", duplicate),
        ("unknown", unknown),
    ):
        if ids:
            problems.append(f"{label} case ids: {', '.join(ids)}")
    if problems:
        raise RecordingError("recording refused: " + "; ".join(problems))


def recorded_file() -> tuple[Path, bool]:
    """The recording to screen and whether it must be complete.

    An owner recording named by ``BRAIN_BUDDY_NAVIGATOR_RECORDED`` is always
    held to completeness; only the committed synthetic sample is partial.
    """

    named = os.environ.get(RECORDED_ENV)
    if named:
        return Path(named), True
    return SAMPLE, False


STALL_REASONS = {
    None,
    "unclear",
    "too_big",
    "missing_info",
    "waiting_on_someone",
    "no_energy",
    "no_longer_matters",
}


def load(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as handle:
        data: dict[str, Any] = json.load(handle)
    return data


def case_input(case: dict[str, Any]) -> NavigatorInput:
    """The FR-019 input of a case, exactly as a client would send it."""

    request = NavigatorSuggestionRequest.model_validate(request_body(case))
    return build_navigator_input(request)


_SMART_ADD = re.compile(r"(?:^|[\s(\[{])[#@!]\S")


def _shape_ok(text: str) -> bool:
    """The screen's own check of rule 1 (independent of the validator)."""

    stripped = text.strip()
    return (
        bool(stripped)
        and len(stripped.splitlines()) == 1
        and len(stripped) <= MAX_PROPOSAL_CHARS
        and _SMART_ADD.search(stripped) is None
    )


def invented(text: str, case: dict[str, Any], navigator_input: NavigatorInput) -> bool:
    """The invented-fact screen: a name, number, amount or date expression
    not covered by the case's ``allowed_entities``, its title, project name or
    sibling titles.

    What counts as a fact is exactly rule 3's trigger (``grounding_terms``:
    lowercase Russian months and relative dates included, a duration of at
    most 30 minutes excepted). Facts from the notes count only when the
    fixture lists them as allowed, so the curated list, not the validator's
    input, is the reference here.
    """

    covered = [
        f" {formulation_key(value)} "
        for value in (
            *case["allowed_entities"],
            navigator_input.task_title,
            navigator_input.project_name,
            *navigator_input.open_task_titles,
        )
        if value
    ]
    return any(
        not any(f" {term} " in value for value in covered)
        for term in grounding_terms(text)
    )


def _empty_bucket() -> dict[str, Any]:
    return {
        "outputs": 0,
        "returned": {"proposals": 0, "question": 0, "malformed": 0},
        "kind_match": 0,
        "raw_invented_facts": 0,
    }


def screen_recorded_outputs(
    eval_set: dict[str, Any],
    recorded: dict[str, Any],
    *,
    require_complete: bool = True,
) -> dict[str, Any]:
    """The deterministic screen runner (aggregate scores only).

    The recording is validated first (``validate_recording``): an incomplete
    or mismatched recording is refused, never scored. Only the committed
    synthetic sample is screened with ``require_complete=False``.

    For every recorded output: the §2 validation (what is shown, or the
    question, or ``malformed``), why each raw proposal was dropped (shape,
    duplicate, grounding), the returned kind against ``expected_kind``, and
    the invented-fact screen before and after validation.
    """

    validate_recording(eval_set, recorded, require_complete=require_complete)
    cases = {case["id"]: case for case in eval_set["cases"]}
    report: dict[str, Any] = {
        "source": recorded["source"],
        "eval_set": recorded["eval_set"],
        "prompt_version": recorded["prompt_version"],
        "outputs": 0,
        "raw_proposals": 0,
        "dropped": {"shape": 0, "duplicate": 0, "grounding": 0},
        "shown_proposals": 0,
        "returned": {"proposals": 0, "question": 0, "malformed": 0},
        "kind_match": 0,
        "raw_invented_facts": 0,
        "invented_facts_after_validation": 0,
        "duplicates_after_validation": 0,
        "shape_violations_after_validation": 0,
        "by_language": {},
    }
    for output in recorded["outputs"]:
        _screen_one(report, cases[output["case_id"]], output)
    return report


def _screen_one(
    report: dict[str, Any], case: dict[str, Any], output: dict[str, Any]
) -> None:
    navigator_input = case_input(case)
    proposals = list(output["proposals"])
    bucket = report["by_language"].setdefault(case["language"], _empty_bucket())
    report["outputs"] += 1
    bucket["outputs"] += 1
    report["raw_proposals"] += len(proposals)
    seen = {formulation_key(navigator_input.task_title or "")}
    seen.update(formulation_key(title) for title in navigator_input.open_task_titles)
    for proposal in proposals:
        if invented(proposal, case, navigator_input):
            report["raw_invented_facts"] += 1
            bucket["raw_invented_facts"] += 1
        key = formulation_key(proposal)
        if not _shape_ok(proposal):
            report["dropped"]["shape"] += 1
        elif key in seen:
            report["dropped"]["duplicate"] += 1
        else:
            seen.add(key)
            if (
                validate_navigator_output(
                    navigator_input, proposals=[proposal], clarifying_question=None
                )
                is None
            ):
                report["dropped"]["grounding"] += 1
    result = validate_navigator_output(
        navigator_input,
        proposals=proposals,
        clarifying_question=output["clarifying_question"],
    )
    if result is None:
        returned = "malformed"
    elif result.proposals is not None:
        returned = "proposals"
        _screen_shown(report, case, navigator_input, result.proposals)
    else:
        returned = "question"
    report["returned"][returned] += 1
    bucket["returned"][returned] += 1
    if returned == case["expected_kind"]:
        report["kind_match"] += 1
        bucket["kind_match"] += 1


def _screen_shown(
    report: dict[str, Any],
    case: dict[str, Any],
    navigator_input: NavigatorInput,
    shown: tuple[str, ...],
) -> None:
    report["shown_proposals"] += len(shown)
    sent = {formulation_key(navigator_input.task_title or "")}
    sent.update(formulation_key(title) for title in navigator_input.open_task_titles)
    keys = [formulation_key(text) for text in shown]
    report["duplicates_after_validation"] += sum(key in sent for key in keys) + (
        len(keys) - len(set(keys))
    )
    report["shape_violations_after_validation"] += sum(
        not _shape_ok(text) for text in shown
    ) + max(0, len(shown) - 3)
    report["invented_facts_after_validation"] += sum(
        invented(text, case, navigator_input) for text in shown
    )


# --------------------------------------------------------------- the set
def test_020_SC_005_eval_set_has_the_planned_shape() -> None:
    """About 48 cases: 24 RU, 12 EN, 12 code-switched; every stall reason and
    none; about 25 % expecting one question; entities and none; 0/5/20
    siblings; every case with ``expected_kind`` and ``allowed_entities``."""

    data = load(EVAL_SET)
    cases = data["cases"]
    assert data["schema"] == "brainbuddy-navigator-eval/v1"
    assert data["prompt_version"] == "navigator-prompt/v1"
    assert len(cases) == 48
    assert len({case["id"] for case in cases}) == 48
    assert Counter(case["language"] for case in cases) == {
        "ru": 24,
        "en": 12,
        "ru-en": 12,
    }
    assert {case["stall_reason"] for case in cases} == STALL_REASONS
    questions = sum(case["expected_kind"] == "question" for case in cases)
    assert 10 <= questions <= 14
    assert {case["expected_kind"] for case in cases} == {"proposals", "question"}
    with_entities = sum(bool(case["allowed_entities"]) for case in cases)
    assert 16 <= with_entities <= 32
    assert {len(case["sibling_titles"]) for case in cases} == {0, 5, 20}
    assert {case["kind"] for case in cases} == {
        "first_step",
        "reformulate",
        "project_next_action",
    }


def test_020_SC_005_every_case_is_a_valid_fr_019_request() -> None:
    """Each case builds a strict ``NavigatorSuggestionRequest`` (no extra
    field, no language) and every allowed entity occurs in its own input."""

    for case in load(EVAL_SET)["cases"]:
        request = NavigatorSuggestionRequest.model_validate(request_body(case))
        assert request.kind == case["kind"]
        haystack = " " + " ".join(input_keys(case_input(case))) + " "
        for entity in case["allowed_entities"]:
            assert f" {formulation_key(entity)} " in haystack, (case["id"], entity)


def request_body(case: dict[str, Any]) -> dict[str, Any]:
    body: dict[str, Any] = {
        "kind": case["kind"],
        "consent": {"external_processing_allowed": True, "provider": "openai"},
    }
    if case["kind"] != "project_next_action":
        body["task"] = {
            "title": case["title"],
            "notes": case["notes"],
            "stall_reason": case["stall_reason"],
        }
    if case["project_name"] is not None:
        body["project"] = {
            "name": case["project_name"],
            "open_task_titles": case["sibling_titles"],
        }
    return body


def input_keys(navigator_input: NavigatorInput) -> list[str]:
    fields = (
        navigator_input.task_title,
        navigator_input.task_notes,
        navigator_input.project_name,
        *navigator_input.open_task_titles,
    )
    return [formulation_key(value) for value in fields if value]


