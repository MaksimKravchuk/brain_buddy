#!/usr/bin/env python3
"""Generate the Carry On design tokens for the apps from their single source.

The source is ``ios/BrainBuddyKit/DesignTokens/carry-on.tokens.json``. This script
writes the Swift the iPhone and Mac apps read (``BrainBuddyDesign/Generated``).
Nothing generated is edited by hand: change the JSON and run this again.

``--check`` writes nothing and exits 1 when a generated file is out of date. The
package test ``DesignTokensTests`` makes the same comparison on every CI run, so a
JSON edit without a regeneration, or a hand edit of the output, fails the kit lanes.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
KIT = ROOT / "ios" / "BrainBuddyKit"
SOURCE = KIT / "DesignTokens" / "carry-on.tokens.json"
GENERATED = KIT / "Sources" / "BrainBuddyDesign" / "Generated"
SWIFT_TOKENS = GENERATED / "CarryOnTokens.swift"
SWIFT_STYLES = GENERATED / "CarryOnTokens+SwiftUI.swift"

HEADER = (
    "// Generated by scripts/generate_design_tokens.py from\n"
    "// ios/BrainBuddyKit/DesignTokens/carry-on.tokens.json. Do not edit by hand:\n"
    "// change the JSON and run `python3 scripts/generate_design_tokens.py`.\n"
)
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def hex_literal(value: str) -> str:
    if not HEX.match(value):
        raise ValueError(f"not a #RRGGBB colour: {value}")
    return "0x" + value[1:].upper()


def number(value: float) -> str:
    return repr(float(value)) if isinstance(value, float) else str(value)


def primitive_name(ref: str) -> str:
    family, step = ref.split(".")
    return f"{camel(family)}{step}"


def render_tokens(tokens: dict[str, Any]) -> str:
    lines: list[str] = [HEADER, "import Foundation", ""]
    table_colors: list[tuple[str, str]] = []
    table_numbers: list[tuple[str, str]] = []

    lines.append("/// Raw palette. Only `CarryOnRole` reads these.")
    lines.append("public enum CarryOnPrimitive {")
    for family, steps in tokens["primitive"].items():
        for step, value in steps.items():
            name = f"{camel(family)}{step}"
            lines.append(
                f"    public static let {name} = RGBColor({hex_literal(value)})"
            )
            table_colors.append(
                (f"primitive.{family}.{step}", f"CarryOnPrimitive.{name}.hex")
            )
    lines += ["}", ""]

    roles = tokens["role"]
    lines.append(
        "/// Semantic roles, light and dark. Components read roles, never primitives."
    )
    lines.append("public enum CarryOnRole {")
    for role, modes in roles.items():
        light, dark = primitive_name(modes["light"]), primitive_name(modes["dark"])
        lines.append(
            f"    public static let {camel(role)} = ThemedColor("
            f"light: CarryOnPrimitive.{light}, dark: CarryOnPrimitive.{dark})"
        )
        for mode in ("light", "dark"):
            table_colors.append(
                (f"role.{role}.{mode}", f"CarryOnRole.{camel(role)}.{mode}.hex")
            )
    lines += ["}", ""]

    lines.append("/// Component tokens. Each points at a role.")
    lines.append("public enum CarryOnComponentColor {")
    for component, role in tokens["component"].items():
        if role not in roles:
            raise ValueError(f"component {component} points at unknown role {role}")
        lines.append(
            f"    public static let {camel(component)} = CarryOnRole.{camel(role)}"
        )
        for mode in ("light", "dark"):
            table_colors.append(
                (
                    f"component.{component}.{mode}",
                    f"CarryOnComponentColor.{camel(component)}.{mode}.hex",
                )
            )
    lines += ["}", ""]

    lines.append("/// Project dots: earth tones, dots only, never text.")
    lines.append("public enum CarryOnProjectColor {")
    for name, value in tokens["project"].items():
        lines.append(
            f"    public static let {camel(name)} = RGBColor({hex_literal(value)})"
        )
        table_colors.append(
            (f"project.{name}", f"CarryOnProjectColor.{camel(name)}.hex")
        )
    lines.append("    public static let all: [ProjectColor] = [")
    for name in tokens["project"]:
        lines.append(f'        ProjectColor(name: "{name}", color: {camel(name)}),')
    lines += ["    ]", "}", ""]

    lines.append("/// The two typefaces and their PostScript names by weight.")
    lines.append("public enum CarryOnFontFace {")
    for face, spec in tokens["font"].items():
        names = ", ".join(
            f'{weight}: "{ps}"' for weight, ps in spec["postscript"].items()
        )
        lines.append(
            f'    public static let {camel(face)} = FontFace(family: "{spec["family"]}", '
            f"postScriptNames: [{names}])"
        )
    lines += ["}", ""]

    lines.append("/// Type styles. iOS and Mac sizes differ; both follow Dynamic Type.")
    lines.append("public enum CarryOnTypeScale {")
    for style, spec in tokens["type"].items():
        if str(spec["weight"]) not in tokens["font"][spec["font"]]["postscript"]:
            raise ValueError(
                f"type {style}: no {spec['font']} face at weight {spec['weight']}"
            )
        lines.append(
            f"    public static let {camel(style)} = TypeStyle("
            f"face: CarryOnFontFace.{camel(spec['font'])}, weight: {spec['weight']}, "
            f"iosSize: {number(spec['ios'])}, macSize: {number(spec['mac'])}, "
            f"lineHeight: {number(spec['lineHeight'])}, tracking: {number(spec['tracking'])}, "
            f".{spec['textStyle']})"
        )
        for field, key in (
            ("weight", "weight"),
            ("ios", "iosSize"),
            ("mac", "macSize"),
            ("lineHeight", "lineHeight"),
            ("tracking", "tracking"),
        ):
            table_numbers.append(
                (
                    f"type.{style}.{field}",
                    f"Double(CarryOnTypeScale.{camel(style)}.{key})",
                )
            )
    lines += ["}", ""]

    for group, doc in (
        ("space", "Spacing scale, in points."),
        ("radius", "Corner radii, in points. `pill` is a capsule."),
    ):
        type_name = f"CarryOn{pascal(group)}"
        lines.append(f"/// {doc}")
        lines.append(f"public enum {type_name} {{")
        for name, value in tokens[group].items():
            lines.append(
                f"    public static let {camel(name)}: Double = {number(value)}"
            )
            table_numbers.append((f"{group}.{name}", f"{type_name}.{camel(name)}"))
        lines += ["}", ""]

    motion = tokens["motion"]
    lines.append(
        "/// Durations in seconds and the one easing curve. Reduce Motion cross-fades."
    )
    lines.append("public enum CarryOnMotion {")
    for name, value in motion.items():
        if name == "ease":
            continue
        lines.append(f"    public static let {camel(name)}: Double = {number(value)}")
        table_numbers.append((f"motion.{name}", f"CarryOnMotion.{camel(name)}"))
    x1, y1, x2, y2 = motion["ease"]
    lines.append(
        f"    public static let ease = CubicBezier(x1: {number(x1)}, y1: {number(y1)}, "
        f"x2: {number(x2)}, y2: {number(y2)})"
    )
    for index, field in enumerate(("x1", "y1", "x2", "y2")):
        table_numbers.append((f"motion.ease.{index}", f"CarryOnMotion.ease.{field}"))
    lines += ["}", ""]

    lines.append("/// Component geometry, in points, exactly as drawn on the boards.")
    lines.append("public enum CarryOnLayout {")
    for component, values in tokens["layout"].items():
        lines.append(f"    public enum {pascal(component)} {{")
        for name, value in values.items():
            lines.append(
                f"        public static let {camel(name)}: Double = {number(value)}"
            )
            table_numbers.append(
                (
                    f"layout.{component}.{name}",
                    f"CarryOnLayout.{pascal(component)}.{camel(name)}",
                )
            )
        lines.append("    }")
    lines += ["}", ""]

    lines.append(
        "/// Every token by its JSON path, for the test that keeps this file in step with the JSON."
    )
    lines.append("public enum CarryOnTokenTable {")
    lines.append("    public static let colors: [String: UInt32] = [")
    lines += [f'        "{key}": {expr},' for key, expr in table_colors]
    lines.append("    ]")
    lines.append("    public static let numbers: [String: Double] = [")
    lines += [f'        "{key}": {expr},' for key, expr in table_numbers]
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_styles(tokens: dict[str, Any]) -> str:
    lines = [HEADER, "#if canImport(SwiftUI)", "import SwiftUI", ""]
    lines.append("extension ShapeStyle where Self == CarryOnColorStyle {")
    lines.append("    // Roles")
    for role in tokens["role"]:
        name = camel(role)
        cap = name[:1].upper() + name[1:]
        lines.append(
            f"    public static var co{cap}: CarryOnColorStyle {{ CarryOnColorStyle(CarryOnRole.{name}) }}"
        )
    lines.append("    // Components")
    for component in tokens["component"]:
        name = camel(component)
        cap = name[:1].upper() + name[1:]
        lines.append(
            f"    public static var co{cap}: CarryOnColorStyle "
            f"{{ CarryOnColorStyle(CarryOnComponentColor.{name}) }}"
        )
    lines += ["}", "#endif"]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if a generated file is stale"
    )
    args = parser.parse_args()

    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    outputs = {SWIFT_TOKENS: render_tokens(tokens), SWIFT_STYLES: render_styles(tokens)}

    stale = [
        path
        for path, text in outputs.items()
        if not path.exists() or path.read_text() != text
    ]
    if args.check:
        for path in stale:
            print(
                f"stale: {path.relative_to(ROOT)}; run python3 scripts/generate_design_tokens.py"
            )
        return 1 if stale else 0
    GENERATED.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
